#!/usr/bin/env python3
"""
sheldon_card_feeder.py
Push Sheldon's Deck characters into the searchsearcher index, one result per
character: its name as the title, its card art as the picture, and a link to
its profile page.

Reads the roster the deck's profile pages are built from
(/games/sheldonsdeck/characters/cards.json, generated by sheldon-the-sheep
scripts/build-character-pages.py from the game's own card array), so search
shows exactly the characters and numbers the game plays.

Usage:
  python3 sheldon_card_feeder.py --dry-run
  INGEST_TOKEN=... python3 sheldon_card_feeder.py [--api http://host:port]
"""

import argparse
import os
import sys

import requests

FEED = "https://sheldon.theofficialblacksheepco.com/games/sheldonsdeck/characters/cards.json"
DEFAULT_API = "https://search.theofficialblacksheepco.com"


def slug(s: str) -> str:
    return "".join(ch if ch.isalnum() else "-" for ch in (s or "").lower()).strip("-")


def build(c: dict, server_name: str) -> dict:
    moves = "\n".join(f"- {m['name'].title()} ({m.get('tag', '')}): {m.get('desc', '')}"
                      for m in c.get("moves", []))
    comps = "\n".join(f"- {x['name']} ({x.get('type', '')}): {x.get('ability', '')}"
                      for x in c.get("companions", []))
    content = c["summary"]
    if moves:
        content += "\n\nMoves:\n" + moves
    if comps:
        content += "\n\nCompanions:\n" + comps
    keywords = ", ".join(dict.fromkeys(x for x in [
        c["name"], c.get("faction"), c.get("rarity"), c.get("powerType"), c.get("secondType"),
        *[m["name"].title() for m in c.get("moves", [])],
        *[x["name"] for x in c.get("companions", [])],
        "Sheldon's Deck", "character", "card"] if x))
    return {
        "serverName": server_name,
        "category": "document",
        "title": c["name"],
        "content": content,
        "keywords": keywords,
        "source": f"sheldon-cards:{c['id']}",
        "tags": ["character", "sheldons-deck", slug(c.get("faction", ""))],
        "status": "active",
        "clearance": 0,
        "metadata": {"url": c["url"], "image": c["image"], "cardId": c["id"],
                     "emoji": c.get("emoji", ""), "rarity": c.get("rarity", ""),
                     "level": c.get("level", ""), "powerType": c.get("powerType", ""),
                     "secondType": c.get("secondType", ""), "faction": c.get("faction", ""),
                     "site": "sheldon.theofficialblacksheepco.com"},
    }


def main():
    ap = argparse.ArgumentParser(description="Push Sheldon's Deck characters into searchsearcher")
    ap.add_argument("--feed", default=FEED)
    ap.add_argument("--api", default=os.getenv("SEARCHSEARCHER_URL", DEFAULT_API))
    ap.add_argument("--token", default=os.getenv("INGEST_TOKEN", ""))
    ap.add_argument("--server-name", default="sheldon-universe")
    ap.add_argument("--dry-run", action="store_true", help="Print payloads, send nothing")
    args = ap.parse_args()

    items = [build(c, args.server_name) for c in requests.get(args.feed, timeout=30).json()]

    if args.dry_run:
        for it in items:
            m = it["metadata"]
            print(f"--- {it['source']}\n    {it['title']} | {m['url']}\n    image: {m['image']}")
        print(f"\nDRY RUN — {len(items)} character(s) would be pushed to {args.api}")
        return
    if not args.token:
        raise SystemExit("no ingest token: pass --token or set INGEST_TOKEN")

    ok = failed = 0
    for it in items:
        try:
            r = requests.post(f"{args.api}/api/ingest", json=it, timeout=30,
                              headers={"Authorization": f"Bearer {args.token}",
                                       "X-Ingest-Token": args.token})
            if r.status_code == 200:
                ok += 1
            else:
                failed += 1
                print(f"✗ {it['source']} → {r.status_code} {r.text[:160]}", file=sys.stderr)
        except Exception as e:
            failed += 1
            print(f"✗ {it['source']} → {e}", file=sys.stderr)
    print(f"Pushed {ok} character(s), {failed} failed → {args.api}")
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
